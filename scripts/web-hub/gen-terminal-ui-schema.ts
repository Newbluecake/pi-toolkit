/** Browser-only JSON-schema projection of the frozen protocol (no runtime TypeBox dependency).
 * Explicit --write updates the generated local consumer; default/--check refuses drift. */
import { readFile, writeFile } from "node:fs/promises";
import { format, resolveConfig } from "prettier";
import { fileURLToPath } from "node:url";
import {
  TerminalConnectionEventSchema,
  TerminalSseEventSchema,
  TERMINAL_HTTP_SCHEMAS,
  TERMINAL_HTTP_SUCCESS_SCHEMAS,
  TERMINAL_OP_ERROR_CODES,
} from "../../src/web-hub/protocol/terminal.js";
export const terminalUiSchemas = () =>
  JSON.parse(
    JSON.stringify({
      connection: TerminalConnectionEventSchema,
      event: TerminalSseEventSchema,
      requests: TERMINAL_HTTP_SCHEMAS,
      results: TERMINAL_HTTP_SUCCESS_SCHEMAS,
      errors: TERMINAL_OP_ERROR_CODES,
    }),
  );
const out = fileURLToPath(new URL("../../src/web-hub/ui/src/components/terminal/protocol-schema.ts", import.meta.url));
const source = `/** Generated by scripts/web-hub/gen-terminal-ui-schema.ts --write.\n * JSON-only projection; the protocol source and drift gate remain authoritative. */\nexport const TERMINAL_UI_SCHEMAS = ${JSON.stringify(terminalUiSchemas(), null, 2)} as const;\n`;
const text = await format(source, { ...(await resolveConfig(out)), filepath: out });
if (process.argv.includes("--write")) await writeFile(out, text);
else if ((await readFile(out, "utf8")) !== text) {
  console.error("terminal UI schema drift; run the explicit generator after reviewing the contract change");
  process.exitCode = 1;
} else console.log("terminal UI schema is current");
