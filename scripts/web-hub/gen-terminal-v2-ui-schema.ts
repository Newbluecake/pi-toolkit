/** T51 P0 v2 projection; explicit --write only. Leaves the v1 generated contract unchanged. */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import {
  TERMINAL_V2_HTTP_SCHEMAS,
  TERMINAL_V2_HTTP_SUCCESS_SCHEMAS,
  TERMINAL_V2_ERROR_STATUS,
  TerminalFailureV2Schema,
  TerminalViewFrameV2Schema,
} from "../../src/web-hub/protocol/terminal-v2.js";
const projection = {
  requests: TERMINAL_V2_HTTP_SCHEMAS,
  results: TERMINAL_V2_HTTP_SUCCESS_SCHEMAS,
  failure: TerminalFailureV2Schema,
  frame: TerminalViewFrameV2Schema,
  errorStatus: TERMINAL_V2_ERROR_STATUS,
};
const out = fileURLToPath(
  new URL("../../src/web-hub/ui/src/components/terminal/protocol-v2-schema.ts", import.meta.url),
);
const source = `/** Generated by scripts/web-hub/gen-terminal-v2-ui-schema.ts --write.\n * JSON-only projection; terminal-v2.ts is authoritative. Not imported by production v1. */\nexport const TERMINAL_V2_UI_SCHEMAS = ${JSON.stringify(projection, null, 2)} as const;\n`;
const text = await format(source, { ...(await resolveConfig(out)), filepath: out });
if (process.argv.includes("--write")) await writeFile(out, text);
else if ((await readFile(out, "utf8")) !== text) {
  console.error("terminal v2 UI schema drift; review contract and run the explicit v2 generator");
  process.exitCode = 1;
} else console.log("terminal v2 UI schema is current");
