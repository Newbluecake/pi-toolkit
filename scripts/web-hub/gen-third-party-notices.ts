function fenceFor(text: string): string {
  let longest = 2;
  for (const m of text.matchAll(/`+/g)) longest = Math.max(longest, m[0].length);
  return "`".repeat(longest + 1);
}

function block(text: string): string {
  const t = text.replace(/\r\n/g, "\n").trimEnd();
  const f = fenceFor(t);
  return `${f}\n${t}\n${f}`;
}

