#!/usr/bin/env -S npx tsx
/**
 * Generates `THIRD_PARTY_NOTICES.md` (web-hub-mermaid plan §8.4, r3 R2-7). Development tool — run by hand
 * whenever `package-lock.json` / the UI bundle's dependency set changes, then commit the result:
 *
 *     npm run build:web                                   # writes node_modules/.cache/pwh-ui-provenance.json
 *     npx vite build --config src/web-hub/ui/vite.config.ts --mode csp-probe   # …/pwh-csp-probe-provenance.json
 *     npx tsx scripts/web-hub/gen-third-party-notices.ts
 *
 * Input = the UNION of the production and csp-probe provenance sidecars (until the UI wires mermaid into the
 * production build, only the probe build carries the whole mermaid closure; notices covering a superset are
 * harmless and `check:web` only demands that every shipped package is covered). Entries come from the
 * packages' ACTUAL rendered modules plus the pinned `src/web-hub/ui/vendored-bundled.json` (components that
 * pre-bundled outer packages embed). Licence texts are copied verbatim from node_modules / the vendored file.
 *
 * Pass `--check` to only verify the file is up to date (no write).
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  noticeHeading,
  readPackageLicenseFiles,
  uniquePackages,
  type NoticePackage,
  type ThirdPartyOverrides,
  type UiProvenance,
  type VendoredBundled,
} from "./lib/ui-provenance.js";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const PROVENANCE_FILES = [
  resolve(REPO_ROOT, "node_modules/.cache/pwh-ui-provenance.json"),
  resolve(REPO_ROOT, "node_modules/.cache/pwh-csp-probe-provenance.json"),
];
const OUT = resolve(REPO_ROOT, "THIRD_PARTY_NOTICES.md");

