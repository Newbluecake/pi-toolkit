interface Entry {
  name: string;
  version: string;
  license: string;
  usedIn: string[];
  texts: string[];
  notices: string[];
  extra: string;
  evidence?: string;
}

export function generate(
  provs: UiProvenance[],
  overrides: ThirdPartyOverrides,
  vendored: VendoredBundled,
): { text: string; problems: string[] } {
  const problems: string[] = [];
  const entries = new Map<string, Entry>();
  const packages = new Map<string, NoticePackage>();
  for (const prov of provs) for (const p of uniquePackages(prov)) packages.set(`${p.name}@${p.version}`, p);

  for (const [id, pkg] of [...packages].sort(([a], [b]) => a.localeCompare(b))) {
    let spdx = pkg.license;
    let evidence: string | undefined;
    if (spdx === null) {
      const o = overrides[id];
      if (!o) {
        problems.push(`${id}: no licence field and no override`);
        continue;
      }
      spdx = o.license;
      evidence = o.evidence;
    }
    const dir = resolve(REPO_ROOT, pkg.dir);
    if (!existsSync(dir)) {
      problems.push(`${id}: ${pkg.dir} is not installed`);
      continue;
    }
    const facts = readPackageLicenseFiles(dir);
    if (facts.licenseTexts.length === 0) problems.push(`${id}: no LICENSE file in ${pkg.dir}`);
    const entry: Entry = {
      name: pkg.name,
      version: pkg.version,
      license: spdx,
      usedIn: ["web-hub browser UI bundle (`dist/web-hub-ui/`)"],
      texts: facts.licenseTexts,
      notices: facts.noticeTexts,
      extra: pkg.name === "elkjs" ? ELK_EXTRA(pkg.version) : "",
    };
    if (evidence !== undefined) entry.evidence = evidence;
    entries.set(id, entry);
  }

  for (const [outer, o] of Object.entries(vendored.outer)) {
    for (const c of o.components) {
      const id = `${c.name}@${c.version}`;
      const existing = entries.get(id);
      if (existing) {
        existing.usedIn.push(`also embedded in the pre-bundled \`${outer}\``);
        continue;
      }
      entries.set(id, {
        name: c.name,
        version: c.version,
        license: c.license ?? "UNKNOWN",
        usedIn: [
          `embedded in the pre-bundled \`${outer}\` (identified from the path comments of its shipped dist files)`,
        ],
        texts: [c.licenseText],
        notices: c.noticeText === null ? [] : [c.noticeText],
        extra: "",
        evidence: c.evidence,
      });
    }
  }

  let out = INTRO;
  for (const e of [...entries.values()].sort((a, b) =>
    `${a.name}@${a.version}`.localeCompare(`${b.name}@${b.version}`),
  )) {
    out += `\n---\n\n${noticeHeading(e.name, e.version)}\n\n- **Version**: ${e.version}\n- **License**: ${e.license}\n`;
    for (const u of e.usedIn) out += `- **Used in**: ${u}\n`;
    if (e.evidence !== undefined) out += `- **Licence evidence**: ${e.evidence}\n`;
    out += "\n";
    for (const t of e.texts) out += `${block(t)}\n\n`;
    for (const n of e.notices) out += `NOTICE file:\n\n${block(n)}\n\n`;
    if (e.extra !== "") out += `${e.extra.trimStart()}\n`;
  }
  return { text: `${out.trimEnd()}\n`, problems };
}

function main(): void {
  const provs: UiProvenance[] = [];
  for (const f of PROVENANCE_FILES) {
    if (existsSync(f)) provs.push(JSON.parse(readFileSync(f, "utf8")) as UiProvenance);
  }
  if (provs.length === 0) {
    console.error("no provenance sidecar found — run `npm run build:web` (and the csp-probe build) first");
    process.exit(1);
  }
  const overrides = JSON.parse(
    readFileSync(resolve(REPO_ROOT, "scripts/web-hub/third-party-overrides.json"), "utf8"),
  ) as ThirdPartyOverrides;
  const vendored = JSON.parse(
    readFileSync(resolve(REPO_ROOT, "src/web-hub/ui/vendored-bundled.json"), "utf8"),
  ) as VendoredBundled;
  const { text, problems } = generate(provs, overrides, vendored);
  if (problems.length > 0) {
    console.error(problems.map((p) => `✗ ${p}`).join("\n"));
    process.exit(1);
  }
  if (process.argv.includes("--check")) {
    const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (current !== text) {
      console.error(
        "✗ THIRD_PARTY_NOTICES.md is out of date — run `npx tsx scripts/web-hub/gen-third-party-notices.ts`",
      );
      process.exit(1);
    }
    console.log("✓ THIRD_PARTY_NOTICES.md is up to date");
    return;
  }
  writeFileSync(OUT, text, "utf8");
  console.log(`✓ wrote ${OUT} (${text.split("\n## ").length - 1} entries)`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
